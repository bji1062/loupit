from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class AboutSection:
    anchor: str
    heading: str
    paragraphs: tuple[str, ...]
    bullets: tuple[str, ...] = ()


@dataclass(frozen=True)
class AboutDoc:
    key: str  # "about" | "contact"
    route: str
    filename: str
    title: str
    lede: str
    meta_description: str
    sections: tuple[AboutSection, ...]
    related: tuple[tuple[str, str], ...]


def _S(anchor, heading, paragraphs, bullets=()) -> AboutSection:
    return AboutSection(anchor, heading, tuple(paragraphs), tuple(bullets))


