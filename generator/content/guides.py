def related_for(doc: GuideDoc, docs: list[GuideDoc], limit: int = 4) -> list[tuple[str, str]]:
    """같은 묶음 형제를 먼저, 부족분은 다른 묶음에서 — 전 문서가 하나의 링크망으로 이어진다.

    회사 페이지가 가나다순 링으로 고아를 없앤 것과 같은 발상이다(GC-26): 크롤러가 어느
    글로 들어와도 나머지에 도달할 수 있어야 색인 자산이 된다.
    """
    others = [d for d in docs if d.slug != doc.slug]
    same = [d for d in others if d.group == doc.group]
    rest = [d for d in others if d.group != doc.group]
    # 형제가 상한을 다 채우면 묶음 밖으로 나가는 링크가 0이 되어 묶음이 폐쇄 싱크가 된다.
    # 최소 1칸은 다른 묶음에 예약한다.
    picked = same[: max(1, limit - 1)] + rest
    return [(d.title, d.route) for d in picked[:limit]]
