def _n(v) -> str:
    """정수 천단위 구분. None 은 “집계 없음” — 0으로 대체하면 사실 주장이 된다."""
    if v is None:
        return "집계 없음"
    return f"{int(round(v)):,}"


def _pct(v) -> str:
    return "집계 없음" if v is None else f"{v:.1f}%"


def _mw(v) -> str:
    return "집계 없음" if v is None else f"{int(round(v)):,}만원"


# 조사 선택 — 앞 낱말의 받침에 따라 갈린다. 카테고리·업종 라벨이 데이터에서 오므로
# 조사를 고정 문자열로 박으면 라벨에 따라 "“보상”로" 같은 비문이 그대로 렌더된다.
_JOSA_PAIRS = {"로": ("로", "으로"), "은": ("는", "은"), "이": ("가", "이"), "를": ("을", "를")}


def _josa(word: str, kind: str) -> str:
    """`word` 뒤에 붙일 조사. `kind` 는 `_JOSA_PAIRS` 의 키 중 하나.

    한글 음절은 유니코드에서 (초성, 중성, 종성) 순서로 배열돼 있어 종성 인덱스를
    산술로 구할 수 있다. 받침 'ㄹ'(종성 인덱스 8)은 '로/으로'에서만 받침 없음과
    같이 취급된다 — “서울로”는 맞고 “서울으로”는 틀리다.
    """
    no_batchim, has_batchim = _JOSA_PAIRS[kind]
    if not word:
        return has_batchim
    code = ord(word[-1])
    if not (0xAC00 <= code <= 0xD7A3):  # 한글 음절이 아니면(숫자·영문) 보수적으로 받침 있음
        return has_batchim
    jong = (code - 0xAC00) % 28
    if jong == 0 or (kind == "로" and jong == 8):
        return no_batchim
    return has_batchim


def _S(anchor, heading, paragraphs, bullets=(), table=None) -> GuideSection:
    return GuideSection(
        anchor=anchor,
        heading=heading,
        paragraphs=tuple(paragraphs),
        bullets=tuple(bullets),
        table=table,
    )


